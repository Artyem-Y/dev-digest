import { createHash } from 'node:crypto';
import { parseUnifiedDiff } from '../src/adapters/git/diff-parser.js';
import { eq } from 'drizzle-orm';
import { afterAll, beforeAll, describe, expect, it, vi } from 'vitest';
import { startPg, dockerAvailable, type PgFixture } from './helpers/pg.js';
import { seed } from '../src/db/seed.js';
import * as t from '../src/db/schema.js';
import { CasesRepository } from '../src/modules/evals/infrastructure/cases-repository.js';
import { createCase } from '../src/modules/evals/application/cases.js';
import { SuiteRepository } from '../src/modules/evals/infrastructure/suite-repository.js';
import { runSuite } from '../src/modules/evals/application/run-suite.js';
import { buildApp } from '../src/app.js';
import { loadConfig } from '../src/platform/config.js';
import { MockGitClient, MockLLMProvider } from '../src/adapters/mocks.js';
import { AgentsRepository } from '../src/modules/agents/repository.js';

const raw = 'diff --git a/synthetic/divide.ts b/synthetic/divide.ts\n--- a/synthetic/divide.ts\n+++ b/synthetic/divide.ts\n@@ -0,0 +1,3 @@\n+export function divide(a: number, b: number) {\n+  return a / b;\n+}\n';
const diffHash = createHash('sha256').update(raw).digest('hex');

const d = await dockerAvailable() ? describe : describe.skip;
d('eval cases on PostgreSQL', () => {
  let pg: PgFixture;
  beforeAll(async () => { pg = await startPg(); await seed(pg.handle.db); }, 120_000);
  afterAll(async () => { await pg?.stop(); });
  it('promotes complete snapshots and rejects stale or legacy runs', async () => {
    const db = pg.handle.db;
    const [workspace] = await db.select().from(t.workspaces);
    const [agent] = await db.insert(t.agents).values({ workspaceId: workspace!.id, name: 'Promotion test', provider: 'openai', model: 'old-model', systemPrompt: 'old prompt' }).returning();
    const [skill] = await db.insert(t.skills).values({ workspaceId: workspace!.id, name: 'Promotion skill', description: '', type: 'custom', source: 'manual', body: 'Check error handling.' }).returning();
    await db.insert(t.agentSkills).values({ agentId: agent!.id, skillId: skill!.id, order: 0, enabled: true });
    const cases = new CasesRepository(db);
    const evalCase = await cases.saveManual(workspace!.id, agent!.id, { name: 'Manual', diff: raw, expectation: 'must_find', anchor: { file: 'synthetic/divide.ts', startLine: 2, endLine: 2 } });
    const suites = new SuiteRepository(db);
    const admitted = await suites.admit(workspace!.id, agent!.id);
    await suites.finish(workspace!.id, admitted.run.id, await runSuite({ review: async () => ({ grounded: [], dropped: 0, costUsd: null }) }, admitted.agent, admitted.cases));
    await db.update(t.agents).set({ systemPrompt: 'new prompt', model: 'new-model', version: 2 }).where(eq(t.agents.id, agent!.id));
    await expect(suites.promote('00000000-0000-0000-0000-000000000000', agent!.id, admitted.run.id, 2)).rejects.toMatchObject({ code: 'not_found' });
    await expect(suites.promote(workspace!.id, agent!.id, admitted.run.id, 1)).rejects.toMatchObject({ code: 'stale_agent' });
    await db.update(t.skills).set({ body: 'Changed skill.' }).where(eq(t.skills.id, skill!.id));
    await expect(suites.promote(workspace!.id, agent!.id, admitted.run.id, 2)).rejects.toMatchObject({ code: 'skills_changed' });
    await db.update(t.skills).set({ body: 'Check error handling.' }).where(eq(t.skills.id, skill!.id));
    const promoted = await suites.promote(workspace!.id, agent!.id, admitted.run.id, 2);
    expect(promoted).toMatchObject({ systemPrompt: 'old prompt', model: 'old-model', version: 3 });
    expect(await db.select().from(t.agentVersions).where(eq(t.agentVersions.agentId, agent!.id))).toHaveLength(1);
    await db.update(t.evalSuiteRuns).set({ snapshot: { agent: admitted.agent, cases: admitted.cases } }).where(eq(t.evalSuiteRuns.id, admitted.run.id));
    await expect(suites.promote(workspace!.id, agent!.id, admitted.run.id, 3)).rejects.toMatchObject({ code: 'snapshot_unavailable' });
    const agents = new AgentsRepository(db);
    const edits = await Promise.all([agents.update(workspace!.id, agent!.id, { systemPrompt: 'Concurrent prompt' }), agents.update(workspace!.id, agent!.id, { model: 'concurrent-model' })]);
    expect(new Set(edits.map((row) => row!.version)).size).toBe(2);
    const versions = await db.select().from(t.agentVersions).where(eq(t.agentVersions.agentId, agent!.id));
    expect(versions.map((row) => row.version).sort()).toEqual([3, 4, 5]);
    await db.update(t.evalSuiteRuns).set({ snapshot: admitted.run.snapshot }).where(eq(t.evalSuiteRuns.id, admitted.run.id));
    const configRace = await Promise.allSettled([suites.promote(workspace!.id, agent!.id, admitted.run.id, 5), agents.update(workspace!.id, agent!.id, { description: 'Concurrent edit' })]);
    expect(configRace.some((item) => item.status === 'fulfilled')).toBe(true);
    const [finalAgent] = await db.select().from(t.agents).where(eq(t.agents.id, agent!.id));
    const finalVersions = await db.select().from(t.agentVersions).where(eq(t.agentVersions.agentId, agent!.id));
    expect(finalVersions.map((row) => row.version).sort()).toEqual(Array.from({ length: finalAgent!.version - 2 }, (_, i) => i + 3));
    const skillRace = await Promise.allSettled([suites.promote(workspace!.id, agent!.id, admitted.run.id, finalAgent!.version), agents.changeSkills(workspace!.id, agent!.id, { kind: 'enabled', id: skill!.id, enabled: false })]);
    expect(skillRace.some((item) => item.status === 'fulfilled')).toBe(true);
    const [lastAgent] = await db.select().from(t.agents).where(eq(t.agents.id, agent!.id));
    const lastVersions = await db.select().from(t.agentVersions).where(eq(t.agentVersions.agentId, agent!.id));
    expect(lastVersions.map((row) => row.version).sort((a, b) => a - b)).toEqual(Array.from({ length: lastAgent!.version - 2 }, (_, i) => i + 3));
    await db.delete(t.agents).where(eq(t.agents.id, agent!.id));
    await db.delete(t.skills).where(eq(t.skills.id, skill!.id));
  });
  it('creates and edits manual cases without rewriting historical snapshots', async () => {
    const db = pg.handle.db;
    const [workspace] = await db.select().from(t.workspaces);
    const [agent] = await db.select().from(t.agents);
    const repository = new CasesRepository(db);
    const input = { name: 'Manual case', diff: raw, expectation: 'must_find' as const, anchor: { file: 'synthetic/divide.ts', startLine: 2, endLine: 2 } };
    const created = await repository.saveManual(workspace!.id, agent!.id, input);
    expect(created.findingId).toBeNull();
    const suites = new SuiteRepository(db);
    const admitted = await suites.admit(workspace!.id, agent!.id, created.id);
    const historical = structuredClone(admitted.run.snapshot);
    await suites.finish(workspace!.id, admitted.run.id, { status: 'failed', results: [], score: null, costUsd: null });
    await repository.saveManual(workspace!.id, agent!.id, { ...input, name: 'Changed', expectation: 'must_not_flag' }, created.id);
    expect((await repository.list(workspace!.id, agent!.id)).find((item) => item.id === created.id)?.expectation).toBe('must_not_flag');
    await expect(repository.saveManual(workspace!.id, agent!.id, input)).rejects.toMatchObject({ code: 'contradictory_labels' });
    expect((await suites.get(workspace!.id, admitted.run.id))!.snapshot).toEqual(historical);
    await expect(repository.saveManual('00000000-0000-0000-0000-000000000000', agent!.id, input, created.id)).rejects.toMatchObject({ code: 'not_found' });
    await expect(repository.saveManual(workspace!.id, agent!.id, { ...input, anchor: { ...input.anchor, file: 'wrong.ts' } })).rejects.toMatchObject({ code: 'invalid_input' });
    await repository.remove(workspace!.id, agent!.id, created.id);
  });
  it('captures immutable source, deduplicates concurrent requests and scopes reads', async () => {
    const db = pg.handle.db;
    const [workspace] = await db.select().from(t.workspaces);
    const [agent] = await db.select().from(t.agents);
    const [pull] = await db.select().from(t.pullRequests);
    const [run] = await db.insert(t.agentRuns).values({ workspaceId: workspace!.id, agentId: agent!.id, prId: pull!.id }).returning();
    const [review] = await db.insert(t.reviews).values({ workspaceId: workspace!.id, prId: pull!.id, agentId: agent!.id, runId: run!.id, kind: 'review' }).returning();
    const [finding] = await db.insert(t.findings).values({ reviewId: review!.id, file: 'synthetic/divide.ts', startLine: 2, endLine: 2, severity: 'WARNING', category: 'bug', title: 'Issue', rationale: 'Issue', confidence: 1, acceptedAt: new Date() }).returning();
    await db.insert(t.evalReviewInputs).values({ workspaceId: workspace!.id, runId: run!.id, input: { diffHash } });
    const unavailable = new CasesRepository(db, async () => parseUnifiedDiff(raw + 'changed'));
    await expect(createCase(unavailable, workspace!.id, finding!.id)).rejects.toMatchObject({ code: 'provenance_unavailable' });
    const repository = new CasesRepository(db, async () => parseUnifiedDiff(raw));
    const results = await Promise.all([createCase(repository, workspace!.id, finding!.id), createCase(repository, workspace!.id, finding!.id)]);
    expect(results.map((result) => result?.created).sort()).toEqual([false, true]);
    expect((await createCase(unavailable, workspace!.id, finding!.id))?.created).toBe(false);
    expect((await repository.list(workspace!.id, agent!.id))[0]).toMatchObject({ fixtureId: 'original-review', expectation: 'must_find' });
    expect(await repository.source('00000000-0000-0000-0000-000000000000', finding!.id, 'synthetic-unchecked-division-v1')).toBeUndefined();
    const engineVersion = `sha256:${'a'.repeat(64)}`;
    const suites = new SuiteRepository(db, engineVersion);
    const admitted = await suites.admit(workspace!.id, agent!.id);
    expect(admitted.run.engineVersion).toBe(engineVersion);
    await expect(suites.admit(workspace!.id, agent!.id)).rejects.toMatchObject({ code: 'active' });
    await suites.markRunning(workspace!.id, admitted.run.id);
    const result = await runSuite({ review: async () => ({ grounded: [{ file: 'synthetic/divide.ts', startLine: 2, endLine: 2 }], dropped: 0, costUsd: null }) }, admitted.agent, admitted.cases);
    await suites.finish(workspace!.id, admitted.run.id, result);
    const stored = await suites.get(workspace!.id, admitted.run.id);
    expect(stored).toMatchObject({ status: 'completed', result: { score: { recall: 1 }, costUsd: null } });
    const single = await suites.admit(workspace!.id, agent!.id, results[0]!.value.id);
    expect(single.cases.map((item) => item.id)).toEqual([results[0]!.value.id]);
    expect(admitted.run.snapshot).toMatchObject({ scope: 'suite' });
    expect(single.run.snapshot).toMatchObject({ scope: 'case' });
    await suites.finish(workspace!.id, single.run.id, result);
    await expect(suites.admit(workspace!.id, agent!.id, '00000000-0000-0000-0000-000000000000')).rejects.toMatchObject({ code: 'not_found' });
    const caseId = results[0]!.value.id;
    expect(await repository.rename(workspace!.id, agent!.id, caseId, 'Renamed')).toBe(true);
    expect((await repository.list(workspace!.id, agent!.id))[0]!.name).toBe('Renamed');
    expect(await repository.remove('00000000-0000-0000-0000-000000000000', agent!.id, caseId)).toBe(false);
    expect(JSON.stringify(stored!.snapshot)).toContain('return a / b');
    const [savedCase] = await db.select().from(t.evalCases);
    expect(savedCase!.inputDiff).toBeNull();
    expect(await repository.remove(workspace!.id, agent!.id, caseId)).toBe(true);
    expect((await suites.get(workspace!.id, admitted.run.id))!.snapshot).toEqual(stored!.snapshot);
    await db.delete(t.evalCases);
    expect(await suites.get('00000000-0000-0000-0000-000000000000', admitted.run.id)).toBeUndefined();
  });
  it('exposes creation and a completed batch through scoped routes', async () => {
    const db = pg.handle.db;
    const [workspace] = await db.select().from(t.workspaces);
    const [agent] = await db.select().from(t.agents);
    const [pull] = await db.select().from(t.pullRequests);
    const [run] = await db.insert(t.agentRuns).values({ workspaceId: workspace!.id, agentId: agent!.id, prId: pull!.id }).returning();
    const [review] = await db.insert(t.reviews).values({ workspaceId: workspace!.id, prId: pull!.id, agentId: agent!.id, runId: run!.id, kind: 'review' }).returning();
    const [finding] = await db.insert(t.findings).values({ reviewId: review!.id, file: 'synthetic/divide.ts', startLine: 2, endLine: 2, severity: 'WARNING', category: 'bug', title: 'Other issue', rationale: 'Issue', confidence: 1, dismissedAt: new Date() }).returning();
    const revisions = { base: 'a'.repeat(40), head: 'b'.repeat(40) };
    await db.insert(t.evalReviewInputs).values({ workspaceId: workspace!.id, runId: run!.id, input: { diffHash, revisions } });
    await db.update(t.pullRequests).set({ base: 'new-base', headSha: 'c'.repeat(40) }).where(eq(t.pullRequests.id, pull!.id));
    const git = new MockGitClient();
    vi.spyOn(git, 'diff').mockResolvedValue(parseUnifiedDiff(raw));
    const provider = new MockLLMProvider('openai', { structured: { verdict: 'approve', summary: 'ok', score: 100, findings: [] } });
    const app = await buildApp({ db, config: loadConfig({ NODE_ENV: 'test' } as NodeJS.ProcessEnv), overrides: { git, llm: { openai: provider, anthropic: provider, openrouter: provider } } });
    try {
      const manual = await app.inject({ method: 'POST', url: `/agents/${agent!.id}/eval-cases`, payload: { name: 'Manual', diff: raw, expectation: 'must_not_flag', anchor: { file: 'synthetic/divide.ts', start_line: 2, end_line: 2 } } });
      expect(manual.statusCode).toBe(201);
      expect(manual.json().finding_id).toBeNull();
      const edited = await app.inject({ method: 'PUT', url: `/agents/${agent!.id}/eval-cases/${manual.json().id}`, payload: { name: 'Updated', diff: raw, expectation: 'must_find', anchor: { file: 'synthetic/divide.ts', start_line: 2, end_line: 2 } } });
      expect(edited.statusCode).toBe(200);
      expect(edited.json().expectation).toBe('must_find');
      expect((await app.inject({ method: 'DELETE', url: `/agents/${agent!.id}/eval-cases/${manual.json().id}` })).statusCode).toBe(200);
      const created = await app.inject({ method: 'POST', url: `/findings/${finding!.id}/eval-cases`, payload: {} });
      expect(created.statusCode).toBe(201);
      expect(git.diff).toHaveBeenCalledWith(expect.objectContaining({ id: pull!.repoId }), revisions.base, revisions.head);
      expect(created.json().expectation).toBe('must_not_flag');
      const caseId = created.json().id;
      const detail = await app.inject({ method: 'GET', url: `/agents/${agent!.id}/eval-cases/${caseId}` });
      expect(detail.statusCode).toBe(200);
      expect(detail.json().diff).toBe(raw);
      const renamed = await app.inject({ method: 'PATCH', url: `/agents/${agent!.id}/eval-cases/${caseId}`, payload: { name: 'Renamed case' } });
      expect(renamed.statusCode).toBe(200);
      expect((await app.inject({ method: 'GET', url: `/agents/${agent!.id}/eval-cases` })).json()[0].name).toBe('Renamed case');
      expect((await app.inject({ method: 'POST', url: `/findings/${finding!.id}/eval-cases`, payload: {} })).statusCode).toBe(200);
      const [unavailableFinding] = await db.insert(t.findings).values({ reviewId: review!.id, file: 'synthetic/divide.ts', startLine: 2, endLine: 2, severity: 'WARNING', category: 'bug', title: 'Unavailable', rationale: 'Issue', confidence: 1, dismissedAt: new Date() }).returning();
      vi.mocked(git.diff).mockRejectedValueOnce(new Error('commit unavailable'));
      const unavailable = await app.inject({ method: 'POST', url: `/findings/${unavailableFinding!.id}/eval-cases`, payload: {} });
      expect(unavailable.statusCode).toBe(409);
      expect(unavailable.json().error.code).toBe('provenance_unavailable');
      const started = await app.inject({ method: 'POST', url: `/agents/${agent!.id}/eval-runs` });
      expect(started.statusCode).toBe(202);
      // Injected adapters are not part of the artifact and cannot share its identity.
      expect(started.json().engine_version).toBe('unavailable');
      expect(JSON.stringify(started.json())).not.toContain('return a / b');
      const id = started.json().id;
      await vi.waitFor(async () => {
        const response = await app.inject({ method: 'GET', url: `/eval-runs/${id}` });
        expect(response.statusCode).toBe(200);
        expect(response.json().status).toBe('completed');
        expect(JSON.stringify(response.json())).not.toContain('return a / b');
      }, { timeout: 10_000 });
      const oneCase = await app.inject({ method: 'POST', url: `/agents/${agent!.id}/eval-cases/${caseId}/runs` });
      expect(oneCase.statusCode).toBe(202);
      expect(oneCase.json().snapshot.cases).toHaveLength(1);
      expect(oneCase.json().snapshot.scope).toBe('case');
      expect(started.json().snapshot.scope).toBe('suite');
      await vi.waitFor(async () => {
        expect((await app.inject({ method: 'GET', url: `/eval-runs/${oneCase.json().id}` })).json().status).toBe('completed');
      }, { timeout: 10_000 });
      expect((await app.inject({ method: 'POST', url: `/agents/${agent!.id}/eval-cases/00000000-0000-0000-0000-000000000000/runs` })).statusCode).toBe(404);
      const batchAgents = await db.insert(t.agents).values(Array.from({ length: 6 }, (_, i) => ({ workspaceId: workspace!.id, name: `Batch ${i}`, provider: 'openai' as const, model: 'mock', systemPrompt: 'review' }))).returning();
      const batchCases = new CasesRepository(db);
      for (const batchAgent of batchAgents) await batchCases.saveManual(workspace!.id, batchAgent.id, { name: 'Batch case', diff: raw, expectation: 'must_find', anchor: { file: 'synthetic/divide.ts', startLine: 2, endLine: 2 } });
      const batch = await app.inject({ method: 'POST', url: '/eval-runs/batch', payload: {} });
      expect(batch.statusCode).toBe(202);
      const startedBatch = batch.json().filter((item: { agent_id: string }) => [agent!.id, ...batchAgents.map((agent) => agent.id)].includes(item.agent_id));
      expect(startedBatch).toHaveLength(7);
      expect(startedBatch.every((item: { run: { snapshot: { scope: string } } }) => item.run.snapshot.scope === 'suite')).toBe(true);
      expect(batch.json().some((item: { error: string }) => item.error === 'empty')).toBe(true);
      await vi.waitFor(async () => { for (const item of startedBatch) expect((await app.inject({ method: 'GET', url: `/eval-runs/${item.run.id}` })).json().status).toBe('completed'); }, { timeout: 10_000 });
      const promote = await app.inject({ method: 'POST', url: `/agents/${agent!.id}/eval-runs/${id}/promote`, payload: { expected_version: agent!.version } });
      expect(promote.statusCode).toBe(200);
      expect(promote.json().version).toBe(agent!.version + 1);
      expect((await app.inject({ method: 'POST', url: `/agents/${agent!.id}/eval-runs/${id}/promote`, payload: { expected_version: agent!.version } })).statusCode).toBe(409);
      for (const url of [`/agents/${agent!.id}/eval-runs`, '/eval-dashboard']) {
        const response = await app.inject({ method: 'GET', url });
        expect(response.statusCode).toBe(200);
        expect(JSON.stringify(response.json())).not.toContain('return a / b');
      }
      const [savedRun] = await db.select().from(t.evalSuiteRuns).where(eq(t.evalSuiteRuns.id, id));
      expect(JSON.stringify(savedRun!.snapshot)).toContain('return a / b');
    } finally { await app.close(); }
  }, 30_000);
});
